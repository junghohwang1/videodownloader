package com.example.videodownloader.youtube

import com.example.videodownloader.download.executeCancellable
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull
import okhttp3.OkHttpClient
import okhttp3.Request
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.io.IOException

/** 자막 한 줄. 시간은 초 단위. */
data class Cue(val start: Double, val end: Double, val text: String)

/** 받은 자막. [languageTag] 가 한국어가 아니면 번역이 필요하다. */
data class FetchedSubtitles(val languageTag: String, val cues: List<Cue>) {
    val isKorean: Boolean get() = languageTag.lowercase().startsWith("ko")
}

/**
 * 유튜브 자막 받기.
 * 우선순위: 한국어 자막 → 한국어 자동 생성 자막 → 영어 자막 → 다른 언어 자막 → 자동 생성 자막(원래 언어).
 * 유튜브의 자동 번역(tlang)은 앱에서 요청하면 봇 차단(HTTP 429)되므로 쓰지 않고, 번역은 기기에서 한다.
 * 자막은 단순한 srv1(XML) 형식으로 받는다. vtt 자동 생성 자막은 앞 줄이 계속 겹쳐 보인다.
 */
object YouTubeSubtitles {

    fun choose(subtitles: List<SubtitlesStream>): SubtitlesStream? {
        val tracks = subtitles.distinctBy { it.languageTag to it.isAutoGenerated }
        fun SubtitlesStream.lang() = languageTag.lowercase()
        val manual = tracks.filter { !it.isAutoGenerated }
        val auto = tracks.filter { it.isAutoGenerated }
        return manual.firstOrNull { it.lang().startsWith("ko") }
            ?: auto.firstOrNull { it.lang().startsWith("ko") }
            ?: manual.firstOrNull { it.lang().startsWith("en") }
            ?: manual.firstOrNull()
            ?: auto.firstOrNull()
    }

    fun srv1Url(stream: SubtitlesStream): String? =
        stream.content.toHttpUrlOrNull()?.newBuilder()?.setQueryParameter("fmt", "srv1")?.build()?.toString()

    /** 가장 알맞은 자막을 받는다. 자막이 없으면 null. */
    suspend fun fetch(client: OkHttpClient, subtitles: List<SubtitlesStream>): FetchedSubtitles? {
        val stream = choose(subtitles) ?: return null
        val url = srv1Url(stream) ?: return null
        val request = Request.Builder().url(url).header("User-Agent", YouTubeSupport.BROWSER_USER_AGENT).build()
        val xml = client.executeCancellable(request) { response ->
            if (!response.isSuccessful) throw IOException("자막을 받을 수 없습니다 (HTTP ${response.code})")
            response.body.string()
        }
        return parseSrv1(xml).takeIf { it.isNotEmpty() }?.let { FetchedSubtitles(stream.languageTag, it) }
    }

    private val TEXT = Regex("""<text\s+start="([\d.]+)"(?:\s+dur="([\d.]+)")?[^>]*>(.*?)</text>""", RegexOption.DOT_MATCHES_ALL)
    private val TAG = Regex("<[^>]+>")
    private val ENTITY = Regex("&(#x[0-9a-fA-F]+|#\\d+|amp|lt|gt|quot|apos);")

    /** `<text start="1.2" dur="3.4">…</text>` 목록을 읽는다. 겹치는 구간은 다음 자막 시작에서 끊는다. */
    fun parseSrv1(xml: String): List<Cue> {
        val raw = TEXT.findAll(xml).mapNotNull { m ->
            val start = m.groupValues[1].toDoubleOrNull() ?: return@mapNotNull null
            val dur = m.groupValues[2].toDoubleOrNull() ?: 2.0
            // 본문이 한 번 더 이스케이프돼 오므로(&amp;#39;) 두 번 푼다.
            val text = unescape(unescape(m.groupValues[3])).replace(TAG, "").trim()
            if (text.isEmpty()) null else Cue(start, start + dur, text)
        }.toList()
        return raw.mapIndexed { i, cue ->
            val next = raw.getOrNull(i + 1)?.start
            if (next != null && next > cue.start && next < cue.end) cue.copy(end = next) else cue
        }
    }

    fun toSrt(cues: List<Cue>): String = buildString {
        cues.forEachIndexed { i, cue ->
            append(i + 1).append('\n')
            append(timestamp(cue.start)).append(" --> ").append(timestamp(cue.end)).append('\n')
            append(cue.text).append("\n\n")
        }
    }

    private fun unescape(s: String): String = ENTITY.replace(s) { m ->
        when (val e = m.groupValues[1]) {
            "amp" -> "&"
            "lt" -> "<"
            "gt" -> ">"
            "quot" -> "\""
            "apos" -> "'"
            else -> {
                val code = if (e.startsWith("#x")) e.drop(2).toIntOrNull(16) else e.drop(1).toIntOrNull()
                code?.let { String(Character.toChars(it)) } ?: m.value
            }
        }
    }

    private fun timestamp(seconds: Double): String {
        val ms = (seconds * 1000).toLong().coerceAtLeast(0)
        return "%02d:%02d:%02d,%03d".format(ms / 3_600_000, ms / 60_000 % 60, ms / 1000 % 60, ms % 1000)
    }
}
